import { parseArgs } from 'node:util';
import { ERROR_ROUTES, type ErrorResponse, type ErrorRoute } from './catalogue.js';
import { GitHubClient, type FetchLike } from './github.js';

export const ISSUE_TITLE_PREFIX = '[error-generator] runtime:';
export const ISSUE_LABEL = 'runtime-errors';
export const ISSUE_LABEL_COLOR = 'B60205';
export const ROUTE_REQUEST_TIMEOUT_MS = 5_000;

export interface CapturedError {
  route: ErrorRoute;
  status: number;
  name: string;
  message: string;
  stack: string;
  capturedAt: string;
}

export interface ReportOptions {
  baseUrl: string;
  repository: string;
  token: string;
  dryRun: boolean;
  fetchImpl?: FetchLike;
  log?: (line: string) => void;
}

export interface ReportResult {
  created: string[];
  skipped: string[];
}

export function issueTitle(captured: CapturedError): string {
  return `${ISSUE_TITLE_PREFIX} ${captured.route.name} (HTTP ${captured.status})`;
}

export function issueBody(captured: CapturedError, baseUrl: string): string {
  return [
    `Generated by the error-generator reporter. This error is intentional and reproducible.`,
    '',
    `| Field | Value |`,
    `| --- | --- |`,
    `| Category | Runtime errors (Category 3) |`,
    `| Route | \`${captured.route.path}\` |`,
    `| HTTP status | ${captured.status} |`,
    `| Error name | \`${captured.name}\` |`,
    `| Summary | ${captured.route.summary} |`,
    `| Captured at | ${captured.capturedAt} |`,
    `| Service | ${baseUrl} |`,
    '',
    '```text',
    captured.stack,
    '```',
    '',
    `Reproduce: \`curl -i ${baseUrl}${captured.route.path}\``,
  ].join('\n');
}

export async function captureRoute(
  baseUrl: string,
  route: ErrorRoute,
  fetchImpl: FetchLike,
): Promise<CapturedError> {
  const response = await fetchImpl(`${baseUrl}${route.path}`, {
    signal: AbortSignal.timeout(ROUTE_REQUEST_TIMEOUT_MS),
  });
  const text = await response.text();
  let parsed: ErrorResponse | undefined;
  try {
    parsed = JSON.parse(text) as ErrorResponse;
  } catch {
    parsed = undefined;
  }
  const error = parsed?.error;
  return {
    route,
    status: response.status,
    name: error?.name ?? 'UnknownError',
    message: error?.message ?? text.slice(0, 200),
    stack: error?.stack ?? text,
    capturedAt: new Date().toISOString(),
  };
}

export async function walkRoutes(baseUrl: string, fetchImpl: FetchLike): Promise<CapturedError[]> {
  const captured: CapturedError[] = [];
  for (const route of ERROR_ROUTES) {
    captured.push(await captureRoute(baseUrl, route, fetchImpl));
  }
  return captured;
}

export async function report(options: ReportOptions): Promise<ReportResult> {
  const log = options.log ?? console.log;
  const fetchImpl: FetchLike = options.fetchImpl ?? ((input, init) => fetch(input, init));
  const captured = await walkRoutes(options.baseUrl, fetchImpl);
  const result: ReportResult = { created: [], skipped: [] };

  if (options.dryRun) {
    for (const entry of captured) {
      log(`[dry-run] would create: ${issueTitle(entry)}`);
      log(issueBody(entry, options.baseUrl));
      log('');
      result.created.push(issueTitle(entry));
    }
    return result;
  }

  const client = new GitHubClient({
    token: options.token,
    repository: options.repository,
    fetchImpl,
  });
  await client.ensureLabel(
    ISSUE_LABEL,
    ISSUE_LABEL_COLOR,
    'Intentional runtime errors generated by error-generator',
  );
  const existing = new Set((await client.listOpenIssues(ISSUE_LABEL)).map((issue) => issue.title));

  for (const entry of captured) {
    const title = issueTitle(entry);
    if (existing.has(title)) {
      log(`skip (open issue exists): ${title}`);
      result.skipped.push(title);
      continue;
    }
    const issue = await client.createIssue(title, issueBody(entry, options.baseUrl), [ISSUE_LABEL]);
    log(`created #${issue.number}: ${title} ${issue.html_url}`);
    result.created.push(title);
  }
  return result;
}

function parseCli(argv: string[]): ReportOptions {
  const { values } = parseArgs({
    args: argv,
    options: {
      'dry-run': { type: 'boolean', default: false },
      'base-url': {
        type: 'string',
        default: process.env['ERROR_SERVICE_URL'] ?? 'http://127.0.0.1:3000',
      },
      repository: { type: 'string', default: process.env['GITHUB_REPOSITORY'] ?? '' },
    },
  });
  const dryRun = values['dry-run'];
  const token = process.env['GITHUB_TOKEN'] ?? '';
  if (!dryRun && !token) {
    throw new Error('GITHUB_TOKEN is required unless --dry-run is given');
  }
  if (!dryRun && !values.repository) {
    throw new Error(
      'GITHUB_REPOSITORY (owner/repo) or --repository is required unless --dry-run is given',
    );
  }
  return { baseUrl: values['base-url'], repository: values.repository, token, dryRun };
}

const isMain = process.argv[1]?.endsWith('reporter.ts') ?? false;
if (isMain) {
  report(parseCli(process.argv.slice(2)))
    .then((result) => {
      console.log(`done: ${result.created.length} created, ${result.skipped.length} skipped`);
    })
    .catch((error: unknown) => {
      console.error(error instanceof Error ? error.message : String(error));
      process.exit(1);
    });
}
